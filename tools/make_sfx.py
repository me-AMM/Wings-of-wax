"""Sound effects synthesized with the Python standard library (wave + math + random). 8-bit retro style.
Run:  python tools/make_sfx.py        -> audio/sfx/*.wav and audio/ambience/*.wav
Format: 16-bit mono 22050 Hz WAV, short attack and decay envelopes, every sound normalised to a peak of -3 dB.
Credit: "Sound effects generated by a script during the event". Replace any file with a jsfxr version of the same name."""
import math, random, struct, wave, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
SR = 22050
PEAK = 10 ** (-3 / 20)            # -3 dB
random.seed(7)

# ------------------------------------------------------------------ building blocks
def write(path, samples, normalise=True):
    path.parent.mkdir(parents=True, exist_ok=True)
    m = max((abs(s) for s in samples), default=1.0) or 1.0
    k = PEAK / m if normalise else 1.0
    with wave.open(str(path), "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", int(max(-1.0, min(1.0, s * k)) * 32767)) for s in samples))

def n_of(dur):
    return int(SR * dur)

def env(i, n, attack=0.004, release=0.35):
    """short attack (seconds) and a decay/release over the last `release` fraction of the sound"""
    a = max(1, int(SR * attack))
    r = max(1, int(n * release))
    e = min(1.0, i / a)
    if i > n - r:
        e *= max(0.0, (n - i) / r)
    return e

def lowpass(x, fc):
    a = 1.0 - math.exp(-2.0 * math.pi * fc / SR)
    y = 0.0
    out = []
    for v in x:
        y += (v - y) * a
        out.append(y)
    return out

def osc(kind, f0, dur, f1=None, vol=1.0, attack=0.004, release=0.35):
    n = n_of(dur)
    out = []
    ph = 0.0
    for i in range(n):
        f = f0 + ((f1 if f1 is not None else f0) - f0) * i / n
        ph = (ph + f / SR) % 1.0
        if kind == "square":
            s = 1.0 if ph < 0.5 else -1.0
        elif kind == "saw":
            s = 2.0 * ph - 1.0
        else:
            s = math.sin(2 * math.pi * ph)
        out.append(s * vol * env(i, n, attack, release))
    return out

def noise(dur, vol=1.0, attack=0.002, release=0.6):
    n = n_of(dur)
    return [random.uniform(-1, 1) * vol * env(i, n, attack, release) for i in range(n)]

def seq(*parts):
    out = []
    for p in parts:
        out += p
    return out

def mix(*parts):
    n = max(len(p) for p in parts)
    return [sum(p[i] if i < len(p) else 0.0 for p in parts) for i in range(n)]

def gain(x, g):
    return [v * g for v in x]

