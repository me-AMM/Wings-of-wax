"""Fallback sound effects, synthesized with the Python standard library (wave + math + random).
Run only if audio/sfx is empty:  python tools/make_sfx.py
Writes 8-bit style mono WAVs (22050 Hz, 16-bit samples) into audio/sfx and audio/ambience.
Credit: "sound effects generated by a script during the event". Replace any file with a jsfxr version by using the same name."""
import math, random, struct, wave, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
SR = 22050
random.seed(3)

def write(path, samples):
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "w") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", int(max(-1, min(1, s)) * 30000)) for s in samples))

def env(i, n, a=0.02, r=0.4):
    t = i / n
    return min(1.0, t / a) * (1.0 - t) ** (r * 3)

def tone(freq, dur, vol=0.5, f_end=None, wave_type="square", decay=0.4):
    n = int(SR * dur); out = []; ph = 0.0
    for i in range(n):
        f = freq + ((f_end if f_end else freq) - freq) * i / n
        ph += f / SR
        s = (1.0 if ph % 1 < 0.5 else -1.0) if wave_type == "square" else math.sin(2 * math.pi * ph)
        out.append(s * vol * env(i, n, 0.01, decay))
    return out

def noise(dur, vol=0.4, decay=0.6, lp=0.3):
    n = int(SR * dur); out = []; y = 0.0
    for i in range(n):
        y += (random.uniform(-1, 1) - y) * lp
        out.append(y * vol * env(i, n, 0.005, decay))
    return out

def seq(*parts):
    out = []
    for p in parts:
        out += p
    return out

def mix(a, b):
    n = max(len(a), len(b)); a = a + [0] * (n - len(a)); b = b + [0] * (n - len(b))
    return [x + y for x, y in zip(a, b)]

