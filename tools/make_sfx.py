# ------------------------------------------------------------------ ambience loops: 8 s, seamless (50 ms crossfade)
def seamless(gen, dur=8.0, cross=0.050):
    n = n_of(dur)
    c = n_of(cross)
    x = gen(n + c)
    out = x[:n]
    for i in range(c):                      # the first 50 ms blend into the continuation of the tail: no click at the loop point
        w = i / c
        out[i] = x[i] * w + x[n + i] * (1.0 - w)
    return out

def breath(n):
    raw = lowpass(lowpass([random.uniform(-1, 1) for _ in range(n)], 600), 600)
    return [v * (0.55 + 0.45 * math.sin(2 * math.pi * 0.25 * i / SR)) for i, v in enumerate(raw)]      # slow 0.25 Hz swell

def hab(n):
    return [0.5 * math.sin(2 * math.pi * 60.0 * i / SR) + 0.3 * math.sin(2 * math.pi * 120.4 * i / SR + 0.7) + 0.2 * math.sin(2 * math.pi * 60.3 * i / SR) for i in range(n)]

def recycler(n):
    soft = lowpass([random.uniform(-1, 1) for _ in range(n)], 500)
    return [0.6 * math.sin(2 * math.pi * 180.0 * i / SR) * (0.85 + 0.15 * math.sin(2 * math.pi * 0.5 * i / SR)) + 0.5 * soft[i] for i in range(n)]

